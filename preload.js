// Ponte segura entre a interface e o disco local
const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('educstat', {
  load: (c) => ipcRenderer.invoke('db:load', c),
  save: (c, obj) => ipcRenderer.invoke('db:save', c, obj),
  info: () => ipcRenderer.invoke('db:info'),
  chooseFolder: () => ipcRenderer.invoke('db:chooseFolder'),
  reload: () => ipcRenderer.invoke('app:reload'),
  hash: (senha, sal) => ipcRenderer.invoke('auth:hash', senha, sal),
  saveFile: (nome, dados) => ipcRenderer.invoke('file:save', nome, dados),
  openFile: (exts) => ipcRenderer.invoke('file:open', exts),
  copiaAuto: (t) => ipcRenderer.invoke('db:copiaAuto', t),
  copias: () => ipcRenderer.invoke('db:copias'),
  lerCopia: (n) => ipcRenderer.invoke('db:lerCopia', n),
  openFiles: (exts, pasta) => ipcRenderer.invoke('file:openMany', exts, pasta),
  importAccess: (opts) => ipcRenderer.invoke('access:import', opts),
  mdbOpen: () => ipcRenderer.invoke('mdb:open'),
  mdbRows: (t, o) => ipcRenderer.invoke('mdb:rows', t, o),
  mdbAll: (t, o) => ipcRenderer.invoke('mdb:all', t, o),
  mdbConvert: (opts) => ipcRenderer.invoke('mdb:convert', opts),
  accessExport: (fichas, alfa) => ipcRenderer.invoke('access:export', fichas, alfa),
  accessCsv: (fichas, alfa) => ipcRenderer.invoke('access:csv', fichas, alfa),
  savePart: (c, parte, obj) => ipcRenderer.invoke('db:savePart', c, parte, obj),
  fimMigracao: (c) => ipcRenderer.invoke('db:fimMigracao', c),
  relPdf: (html, nome, opts) => ipcRenderer.invoke('rel:pdf', html, nome, opts),
  xlsxGraficos: (buf, g) => ipcRenderer.invoke('xlsx:graficos', buf, g),
  relDocx: (doc, nome) => ipcRenderer.invoke('rel:docx', doc, nome),
  janela: (a) => ipcRenderer.invoke('janela:accao', a),
  segChave: (op, v) => ipcRenderer.invoke('seg:chave', op, v),
  servidor: (op, s) => ipcRenderer.invoke('net:servidor', op, s),
  lerShapefile: () => ipcRenderer.invoke('geo:shp'),
  selar: (obj) => ipcRenderer.invoke('pac:selar', obj),
  abrirPacote: (buf) => ipcRenderer.invoke('pac:abrir', buf),
  netSync: (cfg, op, arg) => ipcRenderer.invoke('net:sync', cfg, op, arg),
  cfgComputador: (op, a) => ipcRenderer.invoke('cfg:computador', op, a),
  aoFechar: (fn) => ipcRenderer.on('app:fechar', () => fn()),
  prontoFechar: () => ipcRenderer.send('app:prontoFechar'),
  entrar: (utilizador, senha) => ipcRenderer.invoke('auth:entrar', { utilizador, senha }),
  recuperacao: (op, dados) => ipcRenderer.invoke('auth:recuperacao', op, dados),
  copiarImagem: (dataURL) => ipcRenderer.invoke('img:clip', dataURL),
  entrarVisitante: () => ipcRenderer.invoke('auth:visitante'),
  sair: () => ipcRenderer.invoke('auth:sair'),
  // arrastar ficheiros para o programa: o caminho de cada ficheiro largado segue para o processo principal
  largar: (files) => { const l = []; for (const f of files || []) { try { const c = webUtils.getPathForFile(f); if (c) l.push(c); } catch {} } ipcRenderer.send('largar:definir', l); return l.map((c) => c.split(/[\\/]/).pop()); },
  aoRecusarLargado: (fn) => ipcRenderer.on('largar:recusado', (_e, x) => fn(x)),
});
